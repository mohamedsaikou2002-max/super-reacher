export function listRegistrySourceStatuses(): Record<RegistrySourceStatus, number> {
  return REGISTRY_SOURCE_CATALOG.reduce<Record<RegistrySourceStatus, number>>(
    (acc, item) => {
      acc[item.crawl_status] = (acc[item.crawl_status] ?? 0) + 1;
      return acc;
    },
    {
      verify_before_enable: 0,
      needs_review: 0,
      manual_only: 0,
      blocked_by_terms: 0,
      no_verified_source: 0,
      available: 0,
    },
  );
}
